func TestRefundInvoiceSplitDefaultsAndFIFO(t *testing.T) {
	f := newRefundFinanceFixture(t)
	first := seedRefundFinanceOrder(t, f.user.Id, 100, 9000, 0, 100)
	require.NoError(t, DB.Model(first).Update("invoice_type", "").Error)
	second := seedRefundFinanceOrder(t, f.user.Id, 100, 6000, 360, 200)
	third := seedRefundFinanceOrder(t, f.user.Id, 100, 7000, 0, 300)
	require.NoError(t, DB.Model(third).Update("invoice_type", "none").Error)
	require.NoError(t, DB.Model(&User{}).Where("id = ?", f.user.Id).Updates(map[string]any{"quota": 260, "used_quota": 40}).Error)
	config, err := GetInvoiceTaxConfig(DB)
	require.NoError(t, err)
	assert.False(t, config.SeparateRefundInvoiceTypes)
	mixed, err := quoteRefundFinanceTx(DB, f.user.Id, 260)
	require.NoError(t, err)
	require.Len(t, mixed.Allocations, 3)
	assert.Equal(t, int64(18400), mixed.RefundCashCents)
	assert.Empty(t, mixed.RefundOrderType)
	config.SeparateRefundInvoiceTypes = true
	require.NoError(t, SaveInvoiceTaxConfig(config))
	split, err := quoteRefundFinanceTx(DB, f.user.Id, 260)
	require.NoError(t, err)
	require.Len(t, split.Allocations, 1)
	assert.Equal(t, first.Id, split.Allocations[0].TopUpID)
	assert.Equal(t, int64(40), split.Allocations[0].UsedQuota)
	assert.Equal(t, int64(60), split.Allocations[0].RefundQuota)
	assert.Equal(t, int64(5400), split.RefundCashCents)
	assert.Equal(t, "without_invoice", split.RefundOrderType)
	exact, err := quoteRefundFinanceTx(DB, f.user.Id, 60)
	require.NoError(t, err)
	assert.Equal(t, split.QuoteToken, exact.QuoteToken)
	recordHistoricalRefund(t, f.user.Id, 60)
	next, err := quoteRefundFinanceTx(DB, f.user.Id, 200)
	require.NoError(t, err)
	require.Len(t, next.Allocations, 1)
	assert.Equal(t, second.Id, next.Allocations[0].TopUpID)
	assert.Equal(t, int64(6000), next.RefundCashCents)
	assert.Equal(t, int64(360), next.RefundTaxCents)
	assert.Equal(t, "with_invoice", next.RefundOrderType)
	recordHistoricalRefund(t, f.user.Id, 100)
	last, err := quoteRefundFinanceTx(DB, f.user.Id, 100)
	require.NoError(t, err)
	require.Len(t, last.Allocations, 1)
	assert.Equal(t, third.Id, last.Allocations[0].TopUpID)
	assert.Equal(t, int64(7000), last.RefundCashCents)
}

func TestRefundInvoiceSplitConfirmationAndPolicyChange(t *testing.T) {
	f := newRefundFinanceFixture(t)
	first := seedRefundFinanceOrder(t, f.user.Id, 100, 9000, 0, 100)
	require.NoError(t, DB.Model(first).Update("invoice_type", "none").Error)
	seedRefundFinanceOrder(t, f.user.Id, 100, 6000, 360, 200)
	require.NoError(t, DB.Model(&User{}).Where("id = ?", f.user.Id).Update("quota", 200).Error)
	ticket, _, _, err := CreateRefundTicket(financeRefundParams(f.user, 200))
	require.NoError(t, err)
	mixed, err := QuoteRefundFinance(f.user.Id, 200)
	require.NoError(t, err)
	require.NotEmpty(t, mixed.QuoteToken)
	config, err := GetInvoiceTaxConfig(DB)
	require.NoError(t, err)
	config.SeparateRefundInvoiceTypes = true
	require.NoError(t, SaveInvoiceTaxConfig(config))
	_, err = ConfirmRefundFinance(f.user.Id, ticket.Id, 200, mixed.QuoteToken)
	require.ErrorIs(t, err, ErrInvoiceTaxQuoteChanged)
	split, err := QuoteRefundFinance(f.user.Id, 200)
	require.NoError(t, err)
	_, err = ConfirmRefundFinance(f.user.Id, ticket.Id, 200, split.QuoteToken)
	require.ErrorIs(t, err, ErrInvoiceTaxQuoteChanged)
	confirmed, err := ConfirmRefundFinance(f.user.Id, ticket.Id, 100, split.QuoteToken)
	require.NoError(t, err)
	assert.Equal(t, 100, confirmed.FrozenQuota)
	assert.Equal(t, int64(9000), confirmed.RefundCashCents)
	config.SeparateRefundInvoiceTypes = false
	require.NoError(t, SaveInvoiceTaxConfig(config))
	replay, err := ConfirmRefundFinance(f.user.Id, ticket.Id, 100, split.QuoteToken)
	require.NoError(t, err)
	assert.Equal(t, confirmed.FrozenQuota, replay.FrozenQuota)
}

func TestRefundInvoiceSplitGroupsOrdinaryAndSpecial(t *testing.T) {
	f := newRefundFinanceFixture(t)
	old := seedRefundFinanceOrder(t, f.user.Id, 100, 9000, 0, 100)
	require.NoError(t, DB.Model(old).Update("invoice_type", "").Error)
	seedRefundFinanceOrder(t, f.user.Id, 100, 6000, 360, 200)
	special := seedRefundFinanceOrder(t, f.user.Id, 100, 7000, 630, 300)
	require.NoError(t, DB.Model(special).Update("invoice_type", "special").Error)
	require.NoError(t, DB.Model(&User{}).Where("id = ?", f.user.Id).Updates(map[string]any{"quota": 200, "used_quota": 100}).Error)
	require.NoError(t, SaveInvoiceTaxConfig(InvoiceTaxConfig{Mode: "vat", SeparateRefundInvoiceTypes: true}))
	quote, err := quoteRefundFinanceTx(DB, f.user.Id, 200)
	require.NoError(t, err)
	require.Len(t, quote.Allocations, 2)
	assert.Equal(t, "with_invoice", quote.RefundOrderType)
	assert.Equal(t, int64(13000), quote.RefundCashCents)
	assert.Equal(t, int64(990), quote.RefundTaxCents)
}
